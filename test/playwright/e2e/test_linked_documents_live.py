def _personas(evidence, project, workspace_id, ids, cleanup=False):
    assert project.startswith("ragflow-t1-live-20260906-b-")
    script = """import os,json
from uuid import uuid4
from common import settings
settings.init_settings()
from api.db.db_models import User,UserTenant,Tenant,SourceWorkspace,SourceWorkspaceMember
assert os.environ['POSTGRES_HOST'] == 'postgres'
"""
    script += f"\nworkspace_id={workspace_id!r}\nids={ids!r}\ncleanup={cleanup!r}\n"
    script += """
result={}
with User._meta.database.atomic():
 if cleanup:
  SourceWorkspaceMember.delete().where(SourceWorkspaceMember.user_id.in_(list(ids.values()))).execute()
  UserTenant.delete().where(UserTenant.user_id.in_(list(ids.values()))).execute()
  User.delete().where(User.id.in_(list(ids.values()))).execute()
  Tenant.delete().where(Tenant.id == ids['outsider']).execute()
 else:
  workspace=SourceWorkspace.get_by_id(workspace_id)
  for role,identifier in ids.items():
   user=User.create(id=identifier,nickname='QA '+role,email=identifier+'@example.test',access_token=uuid4().hex,business_document_role='READER')
   if role != 'outsider':
    SourceWorkspaceMember.create(workspace_id=workspace_id,user_id=identifier,role=role)
    if workspace.tenant_id: UserTenant.create(id=uuid4().hex,user_id=identifier,tenant_id=workspace.tenant_id,role='normal',invited_by=workspace.owner_id)
   else:
    Tenant.create(id=identifier,name='QA outsider',llm_id='',embd_id='',asr_id='',img2txt_id='',rerank_id='',parser_ids='')
    UserTenant.create(id=uuid4().hex,user_id=identifier,tenant_id=identifier,role='owner',invited_by=identifier)
   result[role]={'id':identifier,'token':user.get_id()}
print('QA_PERSONAS='+json.dumps(result))
"""
    result = subprocess.run(
        ["docker", "compose", "-p", project, "-f", str(evidence / "compose.yml"), "exec", "-T", "app", "/ragflow/.venv/bin/python", "-"],
        input=script,
        text=True,
        encoding="utf-8",
        capture_output=True,
        timeout=90,
    )
    assert result.returncode == 0, "Disposable persona setup/cleanup failed"
    # Signed synthetic sessions stay in memory; never write subprocess output to evidence.
    return json.loads(next(line.removeprefix("QA_PERSONAS=") for line in result.stdout.splitlines() if line.startswith("QA_PERSONAS=")))


def _fixture(evidence, project, document_id, sequence, workspace_id=None):
    """Synthetic agreed-source history; never connect to the user's running DB."""
    assert project.startswith("ragflow-t1-live-20260906-b-")
    script = """import os
from common import settings
settings.init_settings()
from api.db.db_models import BusinessDocument, BusinessDocumentEvent, BusinessDocumentRevision, User, UserTenant, SourceWorkspace, SourceWorkspaceDraft, SourceDocumentInput, SourceDocumentRevision, SourceDocumentDecision, SourceDocumentChange, SourceDocumentDependency, SourceDocumentImpact
from api.source_workbench.linked_migrations import LINKED_MODELS
assert os.environ['POSTGRES_HOST'] == 'postgres'
actor = User.get(User.email == os.environ['DEFAULT_SUPERUSER_EMAIL']).id
"""
    # All identifiers are generated by this test; repr prevents script injection.
    script += f"\ndocument_id={document_id!r}\nsequence={sequence!r}\nworkspace_id={workspace_id!r}\n"
    script += """
database = BusinessDocument._meta.database
with database.atomic():
 if sequence:
  revision_id = document_id[:24] + str(sequence).zfill(8)
  if sequence == 1:
   tenant = UserTenant.get(UserTenant.user_id == actor).tenant_id
   BusinessDocument.create(id=document_id,tenant_id=tenant,owner_id=actor,chat_id=document_id,title='QA согласованные требования',title_key=document_id,idea='Проверка хранения',template_version='v1',policy_version='v1',current_revision_id=revision_id,lifecycle_state='AGREED')
  BusinessDocument.select().where(BusinessDocument.id == document_id).for_update().get()
  BusinessDocumentRevision.create(id=revision_id,document_id=document_id,revision_number=sequence,document_ast={},body_markdown='# Хранение\\nХранить данные '+('30' if sequence == 1 else '90')+' дней.\\n',content_hash=revision_id,source_event_ids=[])
  BusinessDocumentEvent.create(id=revision_id,document_id=document_id,sequence=sequence,event_type='ReviewAgreedWithoutChanges',actor_type='USER',actor_id=actor,payload={'revision_id':revision_id},correlation_id='linked-live')
  BusinessDocument.update(current_revision_id=revision_id).where(BusinessDocument.id == document_id).execute()
 else:
  if workspace_id:
   ids = list(SourceWorkspaceDraft.select(SourceWorkspaceDraft.id).where(SourceWorkspaceDraft.workspace_id == workspace_id).scalars())
   dependencies = list(SourceDocumentDependency.select(SourceDocumentDependency.id).where(SourceDocumentDependency.workspace_id == workspace_id).scalars())
   SourceDocumentImpact.delete().where(SourceDocumentImpact.dependency_id.in_(dependencies)).execute()
   revisions = SourceDocumentRevision.select(SourceDocumentRevision.id).where(SourceDocumentRevision.document_id.in_(ids))
   changes = SourceDocumentChange.select(SourceDocumentChange.id).where(SourceDocumentChange.workspace_id == workspace_id)
   SourceDocumentDecision.delete().where(SourceDocumentDecision.change_id.in_(changes)).execute()
   SourceDocumentInput.delete().where(SourceDocumentInput.revision_id.in_(revisions)).execute()
   for model in LINKED_MODELS:
    if 'workspace_id' in model._meta.fields: model.delete().where(model.workspace_id == workspace_id).execute()
   SourceDocumentRevision.delete().where(SourceDocumentRevision.document_id.in_(ids)).execute()
   SourceWorkspaceDraft.delete().where(SourceWorkspaceDraft.workspace_id == workspace_id).execute()
   SourceWorkspace.delete().where(SourceWorkspace.id == workspace_id).execute()
   assert not SourceDocumentImpact.select().where(SourceDocumentImpact.dependency_id.in_(dependencies)).exists()
   assert not SourceDocumentRevision.select().where(SourceDocumentRevision.document_id.in_(ids)).exists()
  BusinessDocumentEvent.delete().where(BusinessDocumentEvent.document_id == document_id).execute()
  BusinessDocumentRevision.delete().where(BusinessDocumentRevision.document_id == document_id).execute()
  BusinessDocument.delete().where(BusinessDocument.id == document_id).execute()
print('Synthetic linked fixture operation completed')
"""
    result = subprocess.run(
        ["docker", "compose", "-p", project, "-f", str(evidence / "compose.yml"), "exec", "-T", "app", "/ragflow/.venv/bin/python", "-"],
        input=script,
        text=True,
        encoding="utf-8",
        capture_output=True,
        timeout=90,
    )
    assert result.returncode == 0, "Disposable linked fixture operation failed"


@pytest.mark.auth
def test_approved_source_specification_implementation_instruction(ensure_auth_context, base_url):
    project = os.environ.get("QA_DISPOSABLE_PROJECT", "")
    assert project.startswith("ragflow-t1-live-20260906-b-")
    assert base_url.rstrip("/") == "http://127.0.0.1:19382"
    evidence = Path(os.environ["QA_LIVE_EVIDENCE"])
    page = ensure_auth_context
    headers = {"Authorization": page.evaluate("localStorage.getItem('Authorization')")}
    root = base_url.rstrip("/") + "/api/v1/source-workspaces"
    native_id, workspace = uuid4().hex, None
    manual = "# Ручной раздел\nКонтакт поддержки: отдел эксплуатации.\n"

    def api(path="", method="get", data=None):
        return api_data(getattr(page.request, method)(root + path, headers=headers, **({"data": data} if data is not None else {})))

    def prepare_and_apply(document):
        path = f"/{workspace['id']}/documents/{document['id']}"
        job = api(path + "/prepare", "post", {"expected_version": document["version"]})
        deadline = monotonic() + 600
        while True:
            current = api(path)
            status = next(item for item in current["jobs"] if item["id"] == job["id"])
            assert status["status"] not in {"failed", "cancelled"}, status.get("error")
            if status["status"] == "done":
                break
            assert monotonic() < deadline, "Real model preparation did not finish"
            sleep(2)
        assert current["content"] == document["content"], "Preparation changed canonical text"
        change = next(item for item in current["changes"] if item["id"] == status["result_id"])
        assert change["status"] == "ready" and change["verification"]["verdict"] == "PASS"
        # Apply in the actual editor, correlate the server response, then reload.
        page.goto(base_url.rstrip("/") + "/source-workspaces")
        page.get_by_role("button", name=re.compile(re.escape(workspace["title"]) + r".*")).click()
        page.get_by_role("button", name=re.compile("^" + re.escape(document["title"]) + ":")).click()
        page.get_by_role("button", name="Изменения", exact=True).click()
        with page.expect_response(lambda response: response.request.method == "POST" and response.url.endswith(path + f"/changes/{change['id']}/decision")) as response:
            page.get_by_role("button", name="Подтвердить и применить", exact=True).click()
        applied = api_data(response.value)
        assert "90 дней" in applied["content"] and manual in applied["content"]
        old = api(path + "/revisions/" + document["current_revision_id"])
        assert "30 дней" in "".join(section["text"] for section in old["sections"])
        page.reload()
        assert api(path)["current_revision_id"] == applied["current_revision_id"]
        return applied

    try:
        _fixture(evidence, project, native_id, 1)
        workspace = api(method="post", data={"title": "QA linked " + uuid4().hex[:8], "dataset_ids": []})
        base = "/" + workspace["id"]
        source = api(base + "/documents/import", "post", {"kind": "business_document", "document_id": native_id})
        spec = api(base + "/documents", "post", {"title": "ТЗ хранения", "document_type": "technical_specification", "content": "# Хранение\nХранить данные 30 дней.\n" + manual})
        spec = api(base + f"/documents/{spec['id']}/dependencies", "post", {"source_id": source["id"], "refresh_on": "approved", "expected_version": spec["version"]})
        _fixture(evidence, project, native_id, 2)
        overview = api(base + "/document-overview")
        assert next(row for row in overview["items"] if row["id"] == source["id"])["source_update_available"]
        spec = api(base + f"/documents/{spec['id']}/refresh", "post")
        spec = prepare_and_apply(spec)
        spec = api(base + f"/documents/{spec['id']}/approve", "post", {"expected_version": spec["version"]})
        spec = api(base + f"/documents/{spec['id']}", "put", {"expected_version": spec["version"], "required_for_readiness": True})
        instruction = api(base + "/documents", "post", {"title": "Инструкция хранения", "document_type": "instruction", "content": "# Хранение\nХранить данные 30 дней.\n" + manual})
        instruction = api(base + f"/documents/{instruction['id']}/dependencies", "post", {"source_id": spec["id"], "refresh_on": "implemented", "expected_version": instruction["version"]})
        assert instruction["waiting"] and not instruction["impacts"]
        # Confirm implementation in the browser; approving the source was insufficient.
        page.goto(base_url.rstrip("/") + "/source-workspaces")
        page.get_by_role("button", name=re.compile(re.escape(workspace["title"]) + r".*")).click()
        page.get_by_role("button", name="ТЗ хранения: Подтвердить реализацию", exact=True).click()
        panel = page.get_by_role("region", name="Реализация документа")
        expect(panel).to_be_visible()
        if not panel.get_by_role("button", name="Подтвердить реализацию", exact=True).is_visible():
            panel.get_by_role("button", name="Реализация и история").click()
        with page.expect_response(lambda response: response.request.method == "POST" and response.url.endswith(f"/documents/{spec['id']}/implementation")) as response:
            panel.get_by_role("button", name="Подтвердить реализацию", exact=True).click()
        spec = api_data(response.value)
        instruction = api(base + f"/documents/{instruction['id']}")
        assert not instruction["waiting"] and instruction["impacts"]
        instruction = prepare_and_apply(instruction)
        instruction = api(base + f"/documents/{instruction['id']}/approve", "post", {"expected_version": instruction["version"]})
        instruction = api(base + f"/documents/{instruction['id']}", "put", {"expected_version": instruction["version"], "required_for_readiness": True})
        overview = api(base + "/document-overview")
        assert overview["readiness"]["documents_agreed"] and overview["readiness"]["maintenance_complete"]
        personas = {role: uuid4().hex for role in ("editor", "reviewer", "reader", "outsider")}
        try:
            sessions = _personas(evidence, project, workspace["id"], personas)
            guarded = api(base + "/documents", "post", {"title": "ТЗ проверки полномочий", "content": "# ТЗ\nУтверждённая редакция\n"})
            guarded_url = root + base + "/documents/" + guarded["id"]
            guarded = api(base + f"/documents/{guarded['id']}/approve", "post", {"expected_version": guarded["version"]})
            guarded = api(base + f"/documents/{guarded['id']}", "put", {"expected_version": guarded["version"], "responsible_id": personas["editor"], "approver_id": personas["reviewer"]})
            payload = {"expected_version": guarded["version"], "revision_id": guarded["approved_revision_id"]}
            assert page.request.post(guarded_url + "/implementation", headers=headers, data=payload).status == 403
            for role, session in sessions.items():
                with page.context.browser.new_context(viewport={"width": 1280, "height": 900}) as context:
                    user_info = {"id": session["id"], "nickname": "QA " + role, "access_token": session["token"], "is_superuser": False}
                    context.add_init_script(
                        "localStorage.setItem('Authorization',"
                        + json.dumps(session["token"])
                        + ");localStorage.setItem('token',"
                        + json.dumps(session["token"])
                        + ");localStorage.setItem('userInfo',JSON.stringify("
                        + json.dumps(user_info)
                        + "));localStorage.setItem('lng','ru');"
                    )
                    persona_page = context.new_page()
                    errors = []
                    persona_page.on("pageerror", lambda error: errors.append(str(error)))
                    server_errors = []
                    persona_page.on("response", lambda response: server_errors.append(response.status) if response.status >= 500 and response.url.startswith(base_url) else None)
                    persona_headers = {"Authorization": session["token"]}
                    if role != "editor":
                        assert context.request.post(guarded_url + "/implementation", headers=persona_headers, data=payload).status == (404 if role == "outsider" else 403)
                    with persona_page.expect_response(lambda response: response.request.method == "GET" and response.url.rstrip("/") == root) as listing:
                        persona_page.goto(base_url.rstrip("/") + "/source-workspaces")
                    visible_workspaces = api_data(listing.value)
                    assert (workspace["id"] in {item["id"] for item in visible_workspaces}) is (role != "outsider")
                    workspace_button = persona_page.get_by_role("button", name=re.compile(re.escape(workspace["title"]) + r".*"))
                    if role == "outsider":
                        expect(workspace_button).to_have_count(0)
                    else:
                        workspace_button.click()
                        persona_page.get_by_role("combobox", name="Фильтр документов").select_option("all")
                        persona_page.get_by_role("button", name=re.compile("^ТЗ проверки полномочий:")).click()
                        implementation = persona_page.get_by_role("region", name="Реализация документа")
                        if role == "editor":
                            implementation.get_by_role("button", name="Реализация и история").click()
                            with persona_page.expect_response(lambda response: response.request.method == "POST" and response.url == guarded_url + "/implementation") as response:
                                implementation.get_by_role("button", name="Подтвердить реализацию", exact=True).click()
                            assert api_data(response.value)["implemented_revision_id"] == guarded["approved_revision_id"]
                        else:
                            expect(implementation.get_by_role("button", name="Реализация и история")).to_have_count(0)
                    assert not errors, "Persona page raised an exception"
                    assert not server_errors, "Persona page received an unexpected server error"
        finally:
            _personas(evidence, project, workspace["id"], personas, cleanup=True)
        page.goto(base_url.rstrip("/") + "/source-workspaces")
        page.get_by_role("button", name=re.compile(re.escape(workspace["title"]) + r".*")).click()
        expect(page.get_by_text("Сопровождение завершено: да", exact=True)).to_be_visible()
        (evidence / "linked-documents-proof.json").write_text(
            json.dumps(
                {
                    "real_worker": True,
                    "real_model": True,
                    "native_fixture_agreement": True,
                    "manual_section_preserved": True,
                    "old_revisions_preserved": True,
                    "required_count": overview["readiness"]["required_count"],
                },
                indent=2,
            ),
            encoding="utf-8",
        )
        page.screenshot(path=str(evidence / "linked-documents-complete.png"), full_page=True)
    finally:
        _fixture(evidence, project, native_id, 0, workspace["id"] if workspace else None)
